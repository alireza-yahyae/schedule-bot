// Builds src/tenant-schema.generated.ts from the files in /migrations.
// Every person who uses the public bot gets a private database (src/tenant.ts); this is its schema.
// Run it after you add a migration:  npm run gen:schema   (npm run deploy does it for you)

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
/** Only for the main database (the list of users); a person's own database does not need them. */
const MAIN_ONLY = new Set(['0012_registry.sql']);

/** Split SQL into statements. Understands quotes, comments and CREATE TRIGGER ... BEGIN ... END. */
export function splitSql(sql) {
  const out = [];
  let cur = '';
  let i = 0;
  while (i < sql.length) {
    const c = sql[i];
    const n = sql[i + 1];
    if (c === '-' && n === '-') {
      while (i < sql.length && sql[i] !== '\n') i++;
      continue;
    }
    if (c === '/' && n === '*') {
      const end = sql.indexOf('*/', i + 2);
      i = end < 0 ? sql.length : end + 2;
      continue;
    }
    if (c === "'" || c === '"' || c === '`') {
      let j = i + 1;
      while (j < sql.length) {
        if (sql[j] === c) {
          if (sql[j + 1] === c) j += 2; // doubled quote = escaped quote
          else break;
        } else j++;
      }
      cur += sql.slice(i, j + 1);
      i = j + 1;
      continue;
    }
    if (c === ';') {
      const isTrigger = /^\s*CREATE\s+(?:TEMP(?:ORARY)?\s+)?TRIGGER\b/i.test(cur);
      if (isTrigger && !/\bEND\s*$/i.test(cur.trimEnd())) {
        cur += c;
        i++;
        continue;
      }
      if (cur.trim()) out.push(cur.trim());
      cur = '';
      i++;
      continue;
    }
    cur += c;
    i++;
  }
  if (cur.trim()) out.push(cur.trim());
  return out;
}

/** A new person starts clean: none of the example classes that the first migration puts in the main database. */
function forTenant(file, stmt) {
  if (file === '0002_seed.sql') {
    if (/^INSERT\s+INTO\s+courses\b/i.test(stmt)) return null;
    if (/^INSERT\s+INTO\s+course_sessions\b/i.test(stmt)) return null;
    if (/^INSERT\s+INTO\s+semesters\b/i.test(stmt)) return "INSERT INTO semesters (id, name, is_active) VALUES (1, 'ترم جاری', 1)";
  }
  return stmt;
}

export function buildTenantMigrations(dir = join(root, 'migrations')) {
  const list = [];
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.sql')).sort()) {
    if (MAIN_ONLY.has(file)) continue;
    const statements = splitSql(readFileSync(join(dir, file), 'utf8')).map((s) => forTenant(file, s)).filter((s) => s !== null);
    list.push({ name: file.replace(/\.sql$/, ''), statements });
  }
  // Only for people of the public bot (never for the main database): neutral starting values instead of the owner's personal ones.
  // Written to be safe to run on a database that already has data (it only touches the old personal defaults).
  list.push({
    name: 't001_neutral_defaults',
    statements: [
      `UPDATE settings SET value = '23:30' WHERE key = 'sleep_time' AND value = '07:00'`,
      `UPDATE settings SET value = '07:00' WHERE key = 'wake_time' AND value = '12:00'`,
      `DELETE FROM message_templates WHERE message_text LIKE '%خانم%' OR message_text LIKE '%خانوم%' OR message_text LIKE '%خوشگلم%' OR message_text LIKE '%دختر خوب%'`,
      `UPDATE message_templates SET message_text = REPLACE(message_text, 'دوست\u200cپسر', 'پارتنر') WHERE message_text LIKE '%دوست\u200cپسر%'`,
    ],
  });
  return list;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const list = buildTenantMigrations();
  const body =
    '// GENERATED by scripts/gen-tenant-schema.mjs from /migrations. Do not edit by hand.\n\n' +
    'export const TENANT_MIGRATIONS: { name: string; statements: string[] }[] = ' +
    JSON.stringify(list, null, 1) +
    ';\n';
  writeFileSync(join(root, 'src', 'tenant-schema.generated.ts'), body);
  console.log(`tenant schema: ${list.length} migrations, ${list.reduce((a, m) => a + m.statements.length, 0)} statements`);
}
